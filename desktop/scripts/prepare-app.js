// Builds desktop/app: a copy of the website plus local copies of every library and font it uses,
// so the desktop app works without an internet connection. Run by `npm start` and `npm run dist`.
const fs = require('fs');
const path = require('path');

const SITE = path.resolve(__dirname, '..', '..');
const DESKTOP = path.resolve(__dirname, '..');
const APP = path.join(DESKTOP, 'app');
const MODULES = path.join(DESKTOP, 'node_modules');

// window.LOCAL_ASSETS key → [file or folder in node_modules, destination inside app/vendor]
const ASSETS = {
  pdfLib: ['pdf-lib/dist/pdf-lib.min.js', 'pdf-lib.min.js'],
  pdfjs: ['pdfjs-dist/build/pdf.min.js', 'pdfjs/pdf.min.js'],
  pdfjsWorker: ['pdfjs-dist/build/pdf.worker.min.js', 'pdfjs/pdf.worker.min.js'],
  pdfjsCmaps: ['pdfjs-dist/cmaps', 'pdfjs/cmaps/'],
  pdfjsFonts: ['pdfjs-dist/standard_fonts', 'pdfjs/standard_fonts/'],
  jszip: ['jszip/dist/jszip.min.js', 'jszip.min.js'],
  mammoth: ['mammoth/mammoth.browser.min.js', 'mammoth.browser.min.js'],
  html2canvas: ['html2canvas/dist/html2canvas.min.js', 'html2canvas.min.js'],
  heic2any: ['heic2any/dist/heic2any.min.js', 'heic2any.min.js'],
  sortable: ['sortablejs/Sortable.min.js', 'Sortable.min.js'],
  sheetjs: ['xlsx/dist/xlsx.full.min.js', 'xlsx.full.min.js'],
};
const FONTS = ['@fontsource/press-start-2p', '@fontsource/vt323'];
const LICENSED = ['pdf-lib', 'pdfjs-dist', 'jszip', 'mammoth', 'html2canvas', 'heic2any', 'sortablejs', 'xlsx', ...FONTS];

function copy(from, to) {
  if (!fs.existsSync(from)) throw new Error(`Missing ${path.relative(DESKTOP, from)} — run "npm install" in the desktop folder.`);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
}

function replaceOnce(text, search, replacement) {
  if (!text.includes(search)) throw new Error(`index.html changed: could not find ${JSON.stringify(search)}`);
  return text.replace(search, replacement);
}

fs.rmSync(APP, { recursive: true, force: true });
for (const item of ['index.html', 'css', 'js']) copy(path.join(SITE, item), path.join(APP, item));
copy(path.join(DESKTOP, 'build', 'icon.png'), path.join(APP, 'icon.png'));

// Libraries
const local = {};
for (const [key, [from, to]] of Object.entries(ASSETS)) {
  copy(path.join(MODULES, from), path.join(APP, 'vendor', to));
  local[key] = `vendor/${to}`;
}
fs.writeFileSync(path.join(APP, 'js', 'local-assets.js'),
  `// Generated by desktop/scripts/prepare-app.js: use the bundled libraries instead of CDNs.\nwindow.LOCAL_ASSETS = ${JSON.stringify(local, null, 2)};\n`);

// Fonts (instead of Google Fonts)
const fontLinks = FONTS.map((pkg) => {
  const dir = `vendor/fonts/${path.basename(pkg)}`;
  copy(path.join(MODULES, pkg, 'index.css'), path.join(APP, dir, 'index.css'));
  copy(path.join(MODULES, pkg, 'files'), path.join(APP, dir, 'files'));
  return `<link rel="stylesheet" href="${dir}/index.css">`;
});

// Third-party licences travel with the bundled code.
for (const pkg of LICENSED) {
  const dir = path.join(MODULES, pkg);
  const file = fs.readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  if (file) copy(path.join(dir, file), path.join(APP, 'vendor', 'licenses', `${pkg.replace(/^@/, '').replace('/', '-')}-${file}`));
}

// index.html: local fonts, local library paths, no third-party connections.
let html = fs.readFileSync(path.join(SITE, 'index.html'), 'utf8');
html = html.replace(/\s*<link rel="preconnect"[^>]*>/g, '');
const googleFonts = /<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com[^"]*">/;
if (!googleFonts.test(html)) throw new Error('index.html changed: could not find the Google Fonts stylesheet link');
html = html.replace(googleFonts, fontLinks.join('\n  '));
html = replaceOnce(html, '<script src="js/utils.js"></script>', '<script src="js/local-assets.js"></script>\n  <script src="js/utils.js"></script>');
fs.writeFileSync(path.join(APP, 'index.html'), html);

// Anything left would need the internet (XML namespace URLs inside inline SVG don't count).
const remaining = (html.match(/https?:\/\/[^"'\s)]+/g) || []).filter((u) => !u.startsWith('http://www.w3.org/'));
console.log(`App prepared in ${path.relative(process.cwd(), APP) || APP} (${Object.keys(local).length} libraries, ${FONTS.length} fonts bundled).`);
if (remaining.length) console.log('Note: index.html still references', remaining);
